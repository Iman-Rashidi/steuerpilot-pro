"""German payroll calculation foundation.

Scope: 2026 ordinary full-month employee with statutory health insurance (GKV),
one employer, and standard contribution groups. This module intentionally refuses
special employment/insurance cases until their statutory rules and tests are added.
It does not approximate Lohnsteuer: a verified tax result from the official BMF PAP
adapter is required before a final net-pay result can be produced.
"""
from __future__ import annotations

from dataclasses import dataclass
from decimal import Decimal, ROUND_HALF_UP
from typing import Literal

CENT = Decimal("0.01")
ZERO = Decimal("0.00")


def eur(value: Decimal | str | int) -> Decimal:
    """Convert a value to EUR cents using commercial rounding."""
    return Decimal(str(value)).quantize(CENT, rounding=ROUND_HALF_UP)


def pct(base: Decimal, rate: Decimal) -> Decimal:
    return eur(base * rate / Decimal("100"))


@dataclass(frozen=True)
class PayrollRules:
    year: int = 2026
    kv_cap_monthly: Decimal = Decimal("5812.50")
    rv_av_cap_monthly: Decimal = Decimal("8450.00")
    gkv_general: Decimal = Decimal("14.60")
    gkv_reduced: Decimal = Decimal("14.00")
    gkv_average_additional: Decimal = Decimal("2.90")
    pension: Decimal = Decimal("18.60")
    unemployment: Decimal = Decimal("2.60")
    care_total: Decimal = Decimal("3.60")
    care_employee: Decimal = Decimal("1.80")
    care_employer: Decimal = Decimal("1.80")
    care_saxony_employer: Decimal = Decimal("1.30")
    care_childless_surcharge: Decimal = Decimal("0.60")
    care_child_discount: Decimal = Decimal("0.25")
    midijob_factor_f: Decimal = Decimal("0.6619")
    source_bmas: str = "https://www.bmas.de/DE/Service/Gesetze-und-Gesetzesvorhaben/sozialversicherungs-rechengroessenverordnung-2026.html"
    source_bmg: str = "https://www.bundesgesundheitsministerium.de/beitraege/seite"
    source_minijob: str = "https://www.minijob-zentrale.de/"


@dataclass(frozen=True)
class TaxResult:
    wage_tax: Decimal
    solidarity_surcharge: Decimal
    church_tax: Decimal = ZERO
    source_id: str = ""
    rules_year: int = 2026


@dataclass(frozen=True)
class PayrollInput:
    gross_pay: Decimal
    taxable_gross: Decimal
    social_insurance_gross: Decimal
    state: str
    health_insurance_type: Literal["gkv"] = "gkv"
    health_additional_rate: Decimal = Decimal("2.90")
    health_general_rate: bool = True
    children_under_25: int = 0
    age: int = 30
    church_tax_member: bool = False
    church_tax_rate: Decimal = Decimal("9.00")
    employment_type: Literal["regular"] = "regular"
    insurance_status: Literal["mandatory"] = "mandatory"
    full_month: bool = True
    one_employer: bool = True
    other_deductions: Decimal = ZERO
    advance_payment: Decimal = ZERO


@dataclass(frozen=True)
class PayrollResult:
    gross_pay: Decimal
    taxable_gross: Decimal
    social_insurance_gross: Decimal
    employee_health: Decimal
    employer_health: Decimal
    employee_care: Decimal
    employer_care: Decimal
    employee_pension: Decimal
    employer_pension: Decimal
    employee_unemployment: Decimal
    employer_unemployment: Decimal
    wage_tax: Decimal
    solidarity_surcharge: Decimal
    church_tax: Decimal
    other_deductions: Decimal
    advance_payment: Decimal
    employee_social_total: Decimal
    employer_social_total: Decimal
    net_pay: Decimal
    employer_total_cost_before_other_levies: Decimal
    rules_year: int
    calculation_status: str = "calculated_with_external_bmf_tax_result"


class PayrollInputError(ValueError):
    """Raised when payroll inputs are incomplete or outside supported scope."""


class UnsupportedPayrollCase(PayrollInputError):
    """Raised rather than guessing for an unsupported legal/payroll scenario."""


def calculate_payroll(
    data: PayrollInput,
    tax: TaxResult,
    rules: PayrollRules = PayrollRules(),
) -> PayrollResult:
    """Calculate statutory employee/employer contributions and net pay.

    Lohnsteuer/Soli/Church tax are never estimated here. Callers must supply a
    TaxResult generated by a separately validated implementation of the official
    BMF Programmablaufplan for the same calendar year.
    """
    if rules.year != 2026 or tax.rules_year != rules.year:
        raise UnsupportedPayrollCase("Tax and social-insurance rules must use the same supported year.")
    if data.employment_type != "regular":
        raise UnsupportedPayrollCase("Only ordinary employment is supported; Minijob/Midijob require separate rules.")
    if data.health_insurance_type != "gkv" or data.insurance_status != "mandatory":
        raise UnsupportedPayrollCase("Only mandatory statutory health insurance (GKV) is supported.")
    if not data.full_month:
        raise UnsupportedPayrollCase("Partial-month payroll is not supported by this calculation profile.")
    if not data.one_employer:
        raise UnsupportedPayrollCase("Multiple-employer contribution allocation is not supported.")
    if data.state not in {"BW", "BY", "BE", "BB", "HB", "HH", "HE", "MV", "NI", "NW", "RP", "SL", "SN", "ST", "SH", "TH"}:
        raise PayrollInputError("A valid German Bundesland is required.")
    if data.children_under_25 < 0 or data.children_under_25 > 5:
        raise PayrollInputError("children_under_25 must be between 0 and 5 for this profile.")
    if data.age < 0:
        raise PayrollInputError("age cannot be negative.")
    for name, value in (
        ("gross_pay", data.gross_pay),
        ("taxable_gross", data.taxable_gross),
        ("social_insurance_gross", data.social_insurance_gross),
        ("health_additional_rate", data.health_additional_rate),
        ("other_deductions", data.other_deductions),
        ("advance_payment", data.advance_payment),
        ("wage_tax", tax.wage_tax),
        ("solidarity_surcharge", tax.solidarity_surcharge),
        ("church_tax", tax.church_tax),
    ):
        if Decimal(value) < ZERO:
            raise PayrollInputError(f"{name} cannot be negative.")
    if data.taxable_gross > data.gross_pay or data.social_insurance_gross > data.gross_pay:
        raise PayrollInputError("Taxable/SV gross cannot exceed total gross in this profile.")
    if not tax.source_id:
        raise PayrollInputError("A traceable BMF PAP tax result is required; manual tax figures are not accepted.")
    if data.church_tax_member and tax.church_tax <= ZERO:
        raise PayrollInputError("Church-tax membership requires a church-tax amount from the tax adapter.")
    if not data.church_tax_member and tax.church_tax != ZERO:
        raise PayrollInputError("Church tax cannot be charged when the employee is not a church-tax member.")

    kv_base = min(eur(data.social_insurance_gross), rules.kv_cap_monthly)
    rv_base = min(eur(data.social_insurance_gross), rules.rv_av_cap_monthly)
    kv_rate = (rules.gkv_general if data.health_general_rate else rules.gkv_reduced) + Decimal(data.health_additional_rate)
    employee_health = pct(kv_base, kv_rate / 2)
    employer_health = pct(kv_base, kv_rate / 2)
    employee_pension = pct(rv_base, rules.pension / 2)
    employer_pension = pct(rv_base, rules.pension / 2)
    employee_unemployment = pct(rv_base, rules.unemployment / 2)
    employer_unemployment = pct(rv_base, rules.unemployment / 2)

    saxony = data.state == "SN"
    care_employee_rate = rules.care_employee + (Decimal("0.50") if saxony else ZERO)
    if data.children_under_25 == 0 and data.age >= 23:
        care_employee_rate += rules.care_childless_surcharge
    elif data.children_under_25 >= 2:
        care_employee_rate -= rules.care_child_discount * Decimal(min(data.children_under_25, 5) - 1)
    care_employer_rate = rules.care_saxony_employer if saxony else rules.care_employer
    care_base = min(eur(data.social_insurance_gross), rules.kv_cap_monthly)
    employee_care = pct(care_base, care_employee_rate)
    employer_care = pct(care_base, care_employer_rate)

    employee_social = sum((employee_health, employee_care, employee_pension, employee_unemployment), ZERO)
    employer_social = sum((employer_health, employer_care, employer_pension, employer_unemployment), ZERO)
    wage_tax = eur(tax.wage_tax)
    soli = eur(tax.solidarity_surcharge)
    church_tax = eur(tax.church_tax)
    other = eur(data.other_deductions)
    advance = eur(data.advance_payment)
    net = eur(data.gross_pay) - employee_social - wage_tax - soli - church_tax - other - advance

    return PayrollResult(
        gross_pay=eur(data.gross_pay),
        taxable_gross=eur(data.taxable_gross),
        social_insurance_gross=eur(data.social_insurance_gross),
        employee_health=employee_health,
        employer_health=employer_health,
        employee_care=employee_care,
        employer_care=employer_care,
        employee_pension=employee_pension,
        employer_pension=employer_pension,
        employee_unemployment=employee_unemployment,
        employer_unemployment=employer_unemployment,
        wage_tax=wage_tax,
        solidarity_surcharge=soli,
        church_tax=church_tax,
        other_deductions=other,
        advance_payment=advance,
        employee_social_total=employee_social,
        employer_social_total=employer_social,
        net_pay=eur(net),
        employer_total_cost_before_other_levies=eur(data.gross_pay) + employer_social,
        rules_year=rules.year,
    )
